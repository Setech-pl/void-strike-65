import fs from 'node:fs';
import path from 'node:path';
import {parseTestLog} from '../../../../scripts/reconcile-failures.mjs';
const base=process.argv[2];
if(!base)throw Error('Pass detached main worktree path');
const a=parseTestLog(fs.readFileSync(`${base}/build/npm-test-main.log`,'utf8'),{root:fs.realpathSync(base)});
const b=parseTestLog(fs.readFileSync('build/npm-test.log','utf8'));
if(!a.hasFailingSection||!b.hasFailingSection||!a.totals.tests||!b.totals.tests)throw Error('Complete suites required');
const key=r=>JSON.stringify([r.file,r.test,r.first_failing_assertion,r.message]);
const ak=new Set(a.failures.map(key)),bk=new Set(b.failures.map(key));
const result={mainHead:'7fe9040',main:a.totals,candidate:b.totals,A:b.failures.filter(r=>ak.has(key(r))),B:b.failures.filter(r=>!ak.has(key(r))),C:a.failures.filter(r=>!bk.has(key(r)))};
const rerunPath=`${base}/build/spine-main-fixture-rerun.log`;
const rerun=parseTestLog(fs.readFileSync(rerunPath,'utf8'),{root:fs.realpathSync(base)});
if(rerun.totals.pass!==4||rerun.totals.fail!==0)throw Error('Four repaired main fixture checks must pass');
result.rawC=result.C;
if(result.rawC.length!==4||result.rawC.some(r=>!r.message.includes('has no EMIT_ENEMY_SCORES')))throw Error('Unexpected C requires audit');
result.corrections=result.rawC.map(r=>({test:r.test,reason:'Transient generated-include fixture on main; isolated normal rebuild and focused rerun pass.',evidence:'main-fixture-rerun.log'}));
result.C=[];
result.auditedMain={...a.totals,pass:a.totals.pass+4,fail:a.totals.fail-4};
fs.writeFileSync(new URL('test-comparison.json',import.meta.url),JSON.stringify(result,null,2)+'\n');
console.log({main:a.totals,candidate:b.totals,A:result.A.length,B:result.B.length,C:result.C.length,rawC:result.rawC.length});
if(result.B.length)process.exitCode=1;
