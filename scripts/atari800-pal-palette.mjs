export function atari800PalRgb(value) {
  const rgb = TABLE[(value >> 1) & 0x7f];
  return [(rgb >> 16) & 255, (rgb >> 8) & 255, rgb & 255];
}
// The distance the b3 flash rule reads (docs/plans/boss-art.md §3.3).
export function atari800PalDistance(a, b) {
  const x = atari800PalRgb(a);
  const y = atari800PalRgb(b);
  return Math.hypot(x[0] - y[0], x[1] - y[1], x[2] - y[2]);
}
