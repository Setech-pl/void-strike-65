// Variant C: authored clear masks, never a second packed sprite set.
import fs from 'node:fs';
import {compileHeavyLook} from './enemy-roster.mjs';
export function damageSource() {
  return JSON.parse(fs.readFileSync(new URL('../assets/graphics/enemy-roster.json',import.meta.url)));
}
export function compileHeavyDamage(source=damageSource(),look=compileHeavyLook(source.heavyLooks.armouredRaider)) {
  if(source.heavyDamage?.variant!=='C')throw Error('heavyDamage must select variant C');
  const bodies=[look.subarray(0,16),source.archetypes.find(a=>a.id==='SCYTHE_BOMBER').body.map(r=>parseInt(r,2))];
  const shapes=['armouredRaider','bomber'],bytes=[],stages=[];
  for(const [index,name] of shapes.entries()) {
    const authored=source.heavyDamage[name],body=bodies[index];
    if(!Array.isArray(authored)||authored.length!==2)throw Error(`heavyDamage.${name}: two stages required`);
    const rendered=[];
    for(const [stage,pairs] of authored.entries()) {
      if(!Array.isArray(pairs)||pairs.length!==3)throw Error(`heavyDamage.${name}: three holes per stage required`);
      const result=Array.from(body),seen=new Set();
      for(const pair of pairs) {
        if(!Array.isArray(pair)||pair.length!==2)throw Error('heavyDamage: expected row/mask pair');
        const [row,mask]=pair;
        if(!Number.isInteger(row)||row<1||row>=body.length-1||seen.has(row)||!Number.isInteger(mask)||mask<1||mask>255||(body[row]&mask)!==mask)
          throw Error(`heavyDamage.${name}: invalid row or clear-mask`);
        // Owner 2026-10-31: erode one wing/outline, but keep at least one body
        // bit in every occupied row rather than erase a full row.
        if((body[row]&~mask)===0)throw Error(`heavyDamage.${name}: mask erases an occupied row`);
        seen.add(row);result[row]&=~mask;bytes.push(row,mask);
      }
      if(stage&&result.some((v,row)=>(v&rendered[0][row])!==v))throw Error(`heavyDamage.${name}: stages must be cumulative`);
      rendered.push(result);
    }
    stages.push([Array.from(body),...rendered]);
  }
  return {bytes:Buffer.from(bytes),shapes,stages};
}
export function renderHeavyDamageInclude(compiled) {
  return '; Generated by scripts/heavy-damage.mjs from enemy-roster.json\n.segment "CONTENT_DATA"\n.export heavy_damage_holes\nheavy_damage_holes:\n'+
    [...Array(4)].map((_,i)=>'    .byte '+[...compiled.bytes.subarray(i*6,i*6+6)].map(v=>'$'+v.toString(16).padStart(2,'0')).join(',')).join('\n')+'\n';
}
