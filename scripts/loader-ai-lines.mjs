// M5a-S1: the loader screen's AI lines are creative text, so they are an asset
// (LICENSE-ASSETS, "Mixed files"): authored in assets/text/loader-ai-lines.json
// and converted here into the include src/hybrid/sector-reader.s assembles.
import fs from "node:fs";

// The pool is indexed with a mask, so its line count must be a power of two.
export const LOADER_AI_LINE_COUNT = 4;
export const LOADER_AI_LINE_BYTES = 38;
// render_frontend_data maps only these; anything else would draw a question mark.
const FRONTEND_TEXT = /^[A-Z0-9 \-./:?]*$/;

export function loadLoaderAiLines(sourcePath) {
  const definition = JSON.parse(fs.readFileSync(sourcePath, "utf8"));
  if (definition.format !== 1) throw new Error(`${sourcePath}: unsupported format`);
  if (definition.lineBytes !== LOADER_AI_LINE_BYTES) {
    throw new Error(`${sourcePath}: lineBytes must be ${LOADER_AI_LINE_BYTES}`);
  }
  const { lines } = definition;
  if (!Array.isArray(lines) || lines.length !== LOADER_AI_LINE_COUNT) {
    throw new Error(`${sourcePath}: the pool holds exactly ${LOADER_AI_LINE_COUNT} lines`);
  }
  return lines.map((line, index) => {
    if (typeof line !== "string" || line.length === 0 || line.length > LOADER_AI_LINE_BYTES) {
      throw new Error(`${sourcePath}: line ${index + 1} must be 1-${LOADER_AI_LINE_BYTES} characters`);
    }
    if (!FRONTEND_TEXT.test(line)) {
      throw new Error(`${sourcePath}: line ${index + 1} has a character the frontend charset lacks`);
    }
    return line.padEnd(LOADER_AI_LINE_BYTES, " ");
  });
}

export function renderLoaderAiLinesCa65Include(lines) {
  return [
    "; Generated by scripts/loader-ai-lines.mjs from assets/text/loader-ai-lines.json",
    "; - do not edit. Creative text: CC BY-NC-SA 4.0 (LICENSE-ASSETS).",
    "ai_line_pool:",
    ...lines.map((line, index) => `        .byte "${line}"   ; line ${index + 1}`),
    "ai_line_pool_end:",
    "",
  ].join("\n");
}
